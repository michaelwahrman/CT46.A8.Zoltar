#!/usr/bin/env python3
"""CT46.A8.Zoltar - rebuild the fortune files and the .md -> .html shadows (Linux / WSL):
    python3 tools/build_docs.py
  1. checks CT46.A8.Zoltar_fortunes.json (the master list: ids 1..N, outcome, 75-150 words each)
  2. writes CT46.A8.Zoltar_fortunes.md (for easy inspection)
  3. refreshes the embedded copy of the fortunes inside index.html (needed for file://)
  4. renders every *.md in the project folder to a matching *.md.html shadow
Needs the 'markdown' package (pip install markdown)."""
import json, pathlib, re, html, collections
import markdown

root = pathlib.Path(__file__).resolve().parent.parent
VER = 'CT46.A8.Zoltar'
fortunes = json.loads((root / f'{VER}_fortunes.json').read_text(encoding='utf-8'))
HERMETIC = re.compile(r'Hermes|Hermetic|Kybalion|Emerald Tablet|Thoth|Poimandres|Trismegistus', re.I)

# ---- 1. check
words = lambda t: len(t.split())
assert [f['id'] for f in fortunes] == list(range(1, len(fortunes) + 1)), 'ids must run 1..N'
for f in fortunes:
    assert f['outcome'] in ('favourable', 'warning', 'mixed'), f
    assert 75 <= words(f['text']) <= 150, (f['id'], words(f['text']))
counts = collections.Counter(f['outcome'] for f in fortunes)
herm = [f['id'] for f in fortunes if HERMETIC.search(f['text'])]

# ---- 2. fortunes .md
L = [f'# {VER} — the fortunes', '',
     f'{len(fortunes)} fortunes spoken by Zoltar, written for {VER} (generated by Claude, a generative AI). '
     f'The program reads `{VER}_fortunes.json`; this file is for reading only and is rebuilt from the JSON by `tools/build_docs.py`.', '',
     f'Outcomes: **{counts["favourable"]} favourable**, **{counts["warning"]} warning**, **{counts["mixed"]} mixed / conditional**. '
     f'Word counts {min(words(f["text"]) for f in fortunes)}–{max(words(f["text"]) for f in fortunes)} '
     f'(average {sum(words(f["text"]) for f in fortunes) / len(fortunes):.0f}). '
     f'Hermetic wisdom (Hermes Trismegistus, the Emerald Tablet, the Kybalion, Thoth, the Poimandres) appears in {len(herm)}: '
     + ', '.join(f'#{i}' for i in herm) + '.', '',
     '| # | Title | Outcome | Words |', '|---|---|---|---|']
for f in fortunes:
    L.append(f'| {f["id"]} | [{f["title"]}](#f{f["id"]}) | {f["outcome"]} | {words(f["text"])} |')
L.append('')
for f in fortunes:
    L += ['---', '', f'<a id="f{f["id"]}"></a>', f'## {f["id"]}. {f["title"]}', '',
          f'*Outcome: {f["outcome"]} · {words(f["text"])} words' + (' · Hermetic' if f['id'] in herm else '') + '*', '',
          f['text'], '']
(root / f'{VER}_fortunes.md').write_text('\n'.join(L), encoding='utf-8')

# ---- 3. embedded copy in the page
page = root / 'index.html'
s = page.read_text(encoding='utf-8')
emb = json.dumps(fortunes, ensure_ascii=False, indent=1).replace('</', '<\\/')
s, n = re.subn(r'/\*FORTUNES_BEGIN\*/.*?/\*FORTUNES_END\*/', lambda m: f'/*FORTUNES_BEGIN*/{emb}/*FORTUNES_END*/', s, flags=re.S)
assert n == 1, 'FORTUNES markers not found in the page'
page.write_text(s, encoding='utf-8')

# ---- 4. .md -> .md.html shadows (same look as earlier versions)
HEAD = ('<!doctype html><html lang="en"><head><meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1"><title>{title}</title>\n'
        '<style>body{{max-width:900px;margin:32px auto;padding:0 16px;font:15px/1.55 Georgia,serif;background:#0b0f11;color:#e8dcc4}}\n'
        'h1,h2{{color:#d6aa5c}} a{{color:#e7c07a}} code{{background:#1a2226;padding:1px 4px;border-radius:3px;font-size:13px}}\n'
        'hr{{border:0;border-top:1px solid #33403f;margin:28px 0}}\n'
        'table{{border-collapse:collapse;width:100%}} td,th{{border:1px solid #33403f;padding:6px 8px;vertical-align:top}} th{{background:#162022}}</style>\n'
        '</head><body>')
for md in sorted(root.glob('*.md')):
    text = md.read_text(encoding='utf-8')
    m = re.search(r'^# (.+)$', text, re.M)
    body = markdown.markdown(text, extensions=['tables'])
    (root / (md.name + '.html')).write_text(HEAD.format(title=html.escape(m.group(1) if m else md.stem)) + body + '</body></html>', encoding='utf-8')
    print('rendered', md.name + '.html')
print(f'{len(fortunes)} fortunes OK {dict(counts)}; hermetic {len(herm)}; embedded into {page.name}')
